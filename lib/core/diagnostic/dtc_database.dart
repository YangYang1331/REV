  /// 解释任意故障码：优先精确字典；未收录时按 SAE J2012 / ISO 15031-6
  /// 的码位规则（系统位 + 标准/厂商位 + 子系统位）解析出标准分类与
  /// 通用说明，保证任何合法码都有解释、绝不留白。
  static DtcInfo explain(String rawCode) {
    final code = rawCode.toUpperCase().trim();
    final exact = _data[code];
    if (exact != null) return exact;
    return _decodeByRule(code);
  }

